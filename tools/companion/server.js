// Extract high-definition 960x720 screennail from JPEG APP2 Multi-Picture Format (MPF)
function extractMpfPreview(buf) {
  if (!buf || !Buffer.isBuffer(buf) || buf.length < 100) return null;
  const mpfIdx = buf.indexOf(Buffer.from([0x4D, 0x50, 0x46, 0x00])); // "MPF\0"
  if (mpfIdx === -1) return null;
  const tiffStart = mpfIdx + 4;
  if (tiffStart + 18 >= buf.length) return null;
  const isLE = buf[tiffStart] === 0x49 && buf[tiffStart + 1] === 0x49;
  const readU16 = (o) => (isLE ? buf.readUInt16LE(o) : buf.readUInt16BE(o));
  const readU32 = (o) => (isLE ? buf.readUInt32LE(o) : buf.readUInt32BE(o));
  const ifdOffset = readU32(tiffStart + 4);
  if (tiffStart + ifdOffset + 2 > buf.length) return null;
  const numEntries = readU16(tiffStart + ifdOffset);
  let p = tiffStart + ifdOffset + 2;
  let mpEntryOffset = null;
  for (let i = 0; i < numEntries; i++) {
    if (p + 12 > buf.length) break;
    const tag = readU16(p);
    if (tag === 0xb002) {
      mpEntryOffset = tiffStart + readU32(p + 8);
      break;
    }
    p += 12;
  }
  if (!mpEntryOffset || mpEntryOffset + 32 > buf.length) return null;
  const img2Size = readU32(mpEntryOffset + 16 + 4);
  const img2RelOff = readU32(mpEntryOffset + 16 + 8);
  if (img2Size > 0 && img2RelOff > 0) {
    const absOff = tiffStart + img2RelOff;
    if (absOff + img2Size <= buf.length) {
      return buf.subarray(absOff, absOff + img2Size);
    }
  }
  return null;
}

// Extract compact 160x120 thumbnail from JPEG APP1 EXIF segment
function extractExifThumbnail(buf) {
  if (!buf || !Buffer.isBuffer(buf) || buf.length < 100) return null;
  let offset = 2;
  while (offset < Math.min(buf.length - 4, 131072)) {
    if (buf[offset] === 0xFF && buf[offset + 1] === 0xE1) {
      const len = buf.readUInt16BE(offset + 2);
      const app1 = buf.subarray(offset + 4, offset + 2 + len);
      if (app1.length > 10 && app1.slice(0, 4).toString('ascii') === 'Exif') {
        for (let i = 10; i < app1.length - 4; i++) {
          if (app1[i] === 0xFF && app1[i + 1] === 0xD8) {
            for (let j = app1.length - 2; j > i + 2; j--) {
              if (app1[j] === 0xFF && app1[j + 1] === 0xD9) {
                return app1.subarray(i, j + 2);
              }
            }
          }
        }
      }
      break;
    }
    offset++;
  }
  return null;
}

/**
 * Extracts embedded DJI XMP flight telemetry (GPS, altitude, gimbal pitch/yaw, aircraft model) from a JPEG buffer.
 * @param {Buffer} buf
 * @returns {object|null}
 */
function extractDjiXmpMetadata(buf) {
  if (!buf || !Buffer.isBuffer(buf) || buf.length < 100) return null;
  const searchLimit = Math.min(buf.length, 524288);
  const startIdx = buf.indexOf('<x:xmpmeta', 0, 'utf8');
  if (startIdx === -1 || startIdx > searchLimit) return null;
  const endIdx = buf.indexOf('</x:xmpmeta>', startIdx, 'utf8');
  if (endIdx === -1) return null;

  const xmpStr = buf.subarray(startIdx, endIdx + 12).toString('utf8');
  const result = {};

  const getAttr = (name) => {
    const attrRegex = new RegExp(`drone-dji:${name}="([^"]+)"`, 'i');
    const elemRegex = new RegExp(`<drone-dji:${name}>([^<]+)</drone-dji:${name}>`, 'i');
    const m = xmpStr.match(attrRegex) || xmpStr.match(elemRegex);
    return m ? m[1].trim() : null;
  };

  const latStr = getAttr('GpsLatitude');
  const lonStr = getAttr('GpsLongitude');
  const relAltStr = getAttr('RelativeAltitude');
  const absAltStr = getAttr('AbsoluteAltitude');
  const gimbalPitchStr = getAttr('GimbalPitchDegree');
  const gimbalYawStr = getAttr('GimbalYawDegree');
  const flightPitchStr = getAttr('FlightPitchDegree');
  const flightYawStr = getAttr('FlightYawDegree');
  const flightRollStr = getAttr('FlightRollDegree');
  const modelStr = getAttr('ProductName');
  const createDateMatch = xmpStr.match(/xmp:CreateDate="([^"]+)"/i) || xmpStr.match(/<xmp:CreateDate>([^<]+)<\/xmp:CreateDate>/i)
    || xmpStr.match(/xmp:ModifyDate="([^"]+)"/i) || xmpStr.match(/<xmp:ModifyDate>([^<]+)<\/xmp:ModifyDate>/i);

  if (latStr !== null && !isNaN(parseFloat(latStr))) result.lat = parseFloat(latStr);
  if (lonStr !== null && !isNaN(parseFloat(lonStr))) result.lon = parseFloat(lonStr);
  if (relAltStr !== null && !isNaN(parseFloat(relAltStr))) {
    result.altAgl = parseFloat(relAltStr);
    result.alt = result.altAgl;
  }
  if (absAltStr !== null && !isNaN(parseFloat(absAltStr))) result.altMsl = parseFloat(absAltStr);
  if (gimbalPitchStr !== null && !isNaN(parseFloat(gimbalPitchStr))) result.gimbalPitch = parseFloat(gimbalPitchStr);
  if (gimbalYawStr !== null && !isNaN(parseFloat(gimbalYawStr))) result.heading = parseFloat(gimbalYawStr);
  if (flightPitchStr !== null && !isNaN(parseFloat(flightPitchStr))) result.flightPitch = parseFloat(flightPitchStr);
  if (flightYawStr !== null && !isNaN(parseFloat(flightYawStr))) result.flightYaw = parseFloat(flightYawStr);
  if (flightRollStr !== null && !isNaN(parseFloat(flightRollStr))) result.flightRoll = parseFloat(flightRollStr);
  if (modelStr) result.droneModel = modelStr;
  if (createDateMatch) result.createDate = createDateMatch[1].trim();

  return Object.keys(result).length > 0 ? result : null;
}

/**
 * Calculates MD5 hex checksum of a file on disk via streaming.
 * @param {string} filePath 
 * @returns {Promise<string>}
 */
function computeFileMd5(filePath) {
  return new Promise((resolve, reject) => {
    try {
      const hash = crypto.createHash('md5');
      const stream = fs.createReadStream(filePath);
      stream.on('data', chunk => hash.update(chunk));
      stream.on('end', () => resolve(hash.digest('hex')));
      stream.on('error', err => reject(err));
    } catch (err) {
      reject(err);
    }
  });
}

/**
 * Validates image header/SOI signature for JPEG or TIFF/DNG.
 * @param {string} filePath 
 * @returns {boolean}
 */
function validateImageHeader(filePath) {
  try {
    const fd = fs.openSync(filePath, 'r');
    const headerBuf = Buffer.alloc(4);
    fs.readSync(fd, headerBuf, 0, 4, 0);
    fs.closeSync(fd);
    // JPEG: 0xFFD8
    if (headerBuf[0] === 0xFF && headerBuf[1] === 0xD8) return true;
    // TIFF/DNG: Little-endian 0x49492A00 ('II*\0') or Big-endian 0x4D4D002A ('MM\0*')
    if (headerBuf[0] === 0x49 && headerBuf[1] === 0x49 && headerBuf[2] === 0x2A && headerBuf[3] === 0x00) return true;
    if (headerBuf[0] === 0x4D && headerBuf[1] === 0x4D && headerBuf[2] === 0x00 && headerBuf[3] === 0x2A) return true;
    return false;
  } catch (_) {
    return false;
  }
}


